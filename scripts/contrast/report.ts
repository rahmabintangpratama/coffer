import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Turns the results of tests/e2e/contrast.spec.ts (test-results/contrast/*.json) into docs/contrast-report.md: for every
 * pair, the ratio each engine measured in light and dark, the threshold of the design, and the pairs that do not meet it
 * with the reason the design gives. Run it after the spec has run in the engines you want in the report.
 */
interface Measure {
  id: string;
  kind: string;
  theme: "light" | "dark";
  layer: string;
  detail: string;
  foreground: string;
  background: string;
  ratio: number;
  target: number | null;
  pass: boolean;
  note?: string;
  token?: { name: string; value: string; matches: boolean };
}
interface Run { project: string; theme: "light" | "dark"; userAgent: string; measures: Measure[] }

const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const input = process.argv[2] ?? join(repo, "test-results", "contrast");
const output = process.argv[3] ?? join(repo, "docs", "contrast-report.md");

const runs: Run[] = readdirSync(input)
  .filter((name) => name.endsWith(".json"))
  .map((name) => JSON.parse(readFileSync(join(input, name), "utf8")) as Run);
if (runs.length === 0) {
  console.error(`No results in ${input}. Run: pnpm exec playwright test tests/e2e/contrast.spec.ts`);
  process.exit(1);
}

const engineOf = (project: string) => project.replace(/-\d+$/, "");
const engines = [...new Set(runs.map((run) => engineOf(run.project)))].sort();
const versions = new Map<string, string>();
for (const run of runs) {
  const match = /(Chrome|Firefox|Version)\/([\d.]+)/.exec(run.userAgent);
  versions.set(engineOf(run.project), match ? `${match[1] === "Version" ? "Safari (WebKit)" : (match[1] ?? "")} ${match[2] ?? ""}`.trim() : run.userAgent);
}

const byId = new Map<string, { measure: Measure; ratios: Map<string, number> }>();
for (const run of runs) {
  for (const measure of run.measures) {
    const key = `${measure.theme}|${measure.id}`;
    const entry = byId.get(key) ?? { measure, ratios: new Map<string, number>() };
    entry.ratios.set(engineOf(run.project), measure.ratio);
    byId.set(key, entry);
  }
}
const entries = [...byId.values()];
const failing = entries.filter(({ measure }) => !measure.pass);
const documented = entries.filter(({ measure }) => measure.pass && measure.note !== undefined);
const tokenMismatch = entries.filter(({ measure }) => measure.token && !measure.token.matches);
// Engines that disagree on a ratio by more than a rounding step have painted something different.
const disagree = entries.filter(({ ratios }) => ratios.size > 1 && Math.max(...ratios.values()) - Math.min(...ratios.values()) > 0.05);

const cell = (value: number | undefined) => (value === undefined ? "" : value.toFixed(2));
const lines: string[] = [];
lines.push("# Real-browser contrast report", "");
lines.push("- **Purpose:** the contrast of the colours browsers really paint, measured in Chromium, WebKit and Firefox in light and dark, against the thresholds of the design (technical-spec 15.7, M10).");
lines.push("- **Status:** Generated by `pnpm contrast:report` from `tests/e2e/contrast.spec.ts`. Do not edit by hand.");
lines.push(`- **Last updated:** ${new Date().toISOString().slice(0, 10)}`);
lines.push("- **Source files in design/:** `accessibility.md`, `button-states.md`, `tokens.json`");
lines.push("- **Related:** [ADR-006](adr/ADR-006-danger-tonal-contrast-deviation.md), [technical-spec.md](technical-spec.md#157-verify-contrast-in-a-real-browser-task), [release-checklist.md](release-checklist.md)", "");
const missing = ["chromium", "webkit", "firefox"].filter((engine) => !engines.includes(engine));
lines.push("## Engines", "", ...engines.map((engine) => `- ${engine}: ${versions.get(engine) ?? ""}`), ...missing.map((engine) => `- ${engine}: **not measured in this run**; rerun the spec in it (CI uploads the results as the \`contrast-<project>\` artifact) and regenerate this file`), "");
lines.push("## Result", "");
lines.push(`${entries.length} pairs measured (${runs.length} runs). ${failing.length === 0 ? "Every pair meets its threshold or is a deviation the design documents." : `${failing.length.toString()} pair${failing.length === 1 ? "" : "s"} below the threshold.`} ${tokenMismatch.length === 0 ? "Every painted fill is the token it should be." : `${tokenMismatch.length.toString()} painted fill${tokenMismatch.length === 1 ? "" : "s"} differ${tokenMismatch.length === 1 ? "s" : ""} from the token.`} ${disagree.length === 0 ? "The engines agree on every ratio (within 0.05)." : `${disagree.length.toString()} pair${disagree.length === 1 ? "" : "s"} differ between engines.`}`, "");

if (failing.length > 0) {
  lines.push("### Below the threshold (reopen with the design owner; do not patch locally)", "", "| Theme | Pair | Foreground | Background | Target | " + engines.join(" | ") + " |", "|---|---|---|---|---|" + engines.map(() => "---|").join(""));
  for (const { measure, ratios } of failing) lines.push(`| ${measure.theme} | ${measure.id} | ${measure.foreground} | ${measure.background} | ${(measure.target ?? 0).toString()} | ${engines.map((engine) => cell(ratios.get(engine))).join(" | ")} |`);
  lines.push("");
}
if (documented.length > 0) {
  lines.push("### Deviations the design documents", "", "| Theme | Pair | Target | " + engines.join(" | ") + " | Why it stands |", "|---|---|---|" + engines.map(() => "---|").join("") + "---|");
  for (const { measure, ratios } of documented) lines.push(`| ${measure.theme} | ${measure.id} | ${(measure.target ?? 0).toString()} | ${engines.map((engine) => cell(ratios.get(engine))).join(" | ")} | ${measure.note ?? ""} |`);
  lines.push("");
}
const danger = entries.filter(({ measure }) => measure.id.startsWith("surface/danger-tonal/rest"));
if (danger.length > 0) {
  lines.push("### ADR-006: danger-tonal on the surface layer", "", "| Theme | Part | Foreground | Background | Target | " + engines.join(" | ") + " |", "|---|---|---|---|---|" + engines.map(() => "---|").join(""));
  for (const { measure, ratios } of danger) lines.push(`| ${measure.theme} | ${measure.detail} | ${measure.foreground} | ${measure.background} | ${measure.target === null ? "report" : measure.target.toString()} | ${engines.map((engine) => cell(ratios.get(engine))).join(" | ")} |`);
  lines.push("");
}
lines.push("## All pairs", "", "Ratio as measured, per engine. Foreground and background are from " + (engines[0] ?? "") + ".", "");
for (const theme of ["light", "dark"] as const) {
  lines.push(`### ${theme === "light" ? "Light" : "Dark"}`, "", "| Layer | Pair | Foreground | Background | Target | " + engines.join(" | ") + " | Pass |", "|---|---|---|---|---|" + engines.map(() => "---|").join("") + "---|");
  for (const { measure, ratios } of entries.filter((entry) => entry.measure.theme === theme)) {
    lines.push(`| ${measure.layer} | ${measure.detail} | ${measure.foreground} | ${measure.background} | ${measure.target === null ? "-" : measure.target.toString()} | ${engines.map((engine) => cell(ratios.get(engine))).join(" | ")} | ${measure.pass ? (measure.note ? "documented" : "pass") : "FAIL"} |`);
  }
  lines.push("");
}
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, lines.join("\n"));
console.log(`${output}: ${entries.length} pairs, ${failing.length} below threshold, ${documented.length} documented`);
if (failing.length > 0) process.exit(2);
